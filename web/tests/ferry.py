import sys, json, time; sys.path.insert(0, __file__.rsplit('/', 1)[0])
from harness import run, OUT
def t(g):
    g.hunter(); g.sim(1)
    port = g.js("(() => { const c = HUNT.camps.find(c => ferryPort(c) === 'new'); return c ? [HUNT.camps.indexOf(c), c.tribe] : null; })()")
    print('port', port)
    g.js(f"(() => {{ const c = HUNT.camps[{port[0]}]; P.a.pos.set(c.x + 6, 0, c.z + 6); P.a.ground(1, true); }})()")
    g.sim(3)
    g.js(f"(() => {{ const c = HUNT.camps[{port[0]}], t = c.hunters.find(h => h.alive && !h.young); talkNpc(t); }})()")
    btn = g.js("(() => { const b = document.querySelector('#talkov [data-a=ferry]'); return b ? b.textContent : null; })()")
    print('ferry button:', btn)
    g.page.screenshot(path=f"{OUT}/ferry_talk.png")
    g.js("document.querySelector('#talkov [data-a=ferry]').click()")
    card = g.js("(() => { const e = document.getElementById('ferryov'); return e && !e.hidden ? e.innerText : null; })()")
    print('ferry card:', card)
    g.page.screenshot(path=f"{OUT}/ferry_card.png")
    g.js("document.querySelector('#ferryov [data-k=\"0\"]').click()")
    time.sleep(1.8)
    g.sim(2)
    r = g.js("({ x: Math.round(P.a.pos.x), z: Math.round(P.a.pos.z), land: landAt(P.a.pos.x, P.a.pos.z), flags: PROG.flags.ferry, paused: G.paused })")
    print('arrived', r)
    for k in range(40): g.sim(0.25)
    g.shot('ferry_arrive')
    # and back again from the town of the mills
    g.js("(() => { const c = HUNT.camps.find(c => c.set && c.set.id === 'mill'); const t = c.hunters.find(h => h.alive && !h.young); goldAdd(20); talkNpc(t); })()")
    btn = g.js("(() => { const b = document.querySelector('#talkov [data-a=ferry]'); return b ? b.textContent : null; })()")
    print('ferry back button:', btn)
    g.js("document.querySelector('#talkov [data-a=ferry]').click()")
    card = g.js("(() => { const e = document.getElementById('ferryov'); return e && !e.hidden ? e.innerText : null; })()")
    print('ferry back card:', card)
    g0 = g.js("goldHave()")
    g.js("document.querySelector('#ferryov [data-k=\"0\"]').click()")
    time.sleep(1.8); g.sim(1)
    r = g.js("({ x: Math.round(P.a.pos.x), z: Math.round(P.a.pos.z), land: landAt(P.a.pos.x, P.a.pos.z), gold: goldHave() })")
    print('back', r, 'gold before', g0)
    print('errs', g.errors()[:6])
run(t)
